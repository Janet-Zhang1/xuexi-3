// 解析词汇管理类
export class ParsedVocabularyManager {
  private words: WordWithDetail[];

  constructor(data: WordWithDetail[]) {
    this.words = data;
  }

  // 按字母获取词汇
  getByLetter(letter: string): WordWithDetail[] {
    return this.words.filter(w => w.category === letter.toLowerCase());
  }

  // 搜索词汇
  search(keyword: string): WordWithDetail[] {
    const lowerKeyword = keyword.toLowerCase();
    return this.words.filter(w => 
      w.word.toLowerCase().includes(lowerKeyword) ||
      w.definition.includes(keyword) ||
      w.content.includes(keyword)
    );
  }

  // 获取所有词汇
  getAll(): WordWithDetail[] {
    return this.words;
  }

  // 获取所有分类（字母）
  getCategories(): string[] {
    return Array.from(new Set(this.words.map(w => w.category))).sort();
  }

  // 根据ID获取词汇
  getById(id: number): WordWithDetail | undefined {
    return this.words.find(w => w.id === id);
  }

  // 根据单词获取词汇
  getByWord(word: string): WordWithDetail | undefined {
    const lowerWord = word.toLowerCase();
    return this.words.find(w => w.word.toLowerCase() === lowerWord);
  }
}

