// 词汇管理类
export class VocabularyManager {
  private words: Word[];

  constructor(data: Word[]) {
    this.words = data;
  }

  // 按字母获取词汇
  getByLetter(letter: string): Word[] {
    return this.words.filter(w => w.category === letter.toLowerCase());
  }

  // 搜索词汇
  search(keyword: string): Word[] {
    const lowerKeyword = keyword.toLowerCase();
    return this.words.filter(w => 
      w.word.toLowerCase().includes(lowerKeyword) ||
      w.meaning.includes(keyword)
    );
  }

  // 获取所有词汇
  getAll(): Word[] {
    return this.words;
  }

  // 获取所有分类（字母）
  getCategories(): string[] {
    return Array.from(new Set(this.words.map(w => w.category))).sort();
  }

  // 根据ID获取词汇
  getById(id: number): Word | undefined {
    return this.words.find(w => w.id === id);
  }
}

